<?php

namespace App\Exports;

use App\Models\User;
use Maatwebsite\Excel\Concerns\FromArray;
use Maatwebsite\Excel\Concerns\ShouldAutoSize;
use Maatwebsite\Excel\Concerns\WithColumnFormatting;
use Maatwebsite\Excel\Concerns\WithEvents;
use Maatwebsite\Excel\Concerns\WithStyles;
use Maatwebsite\Excel\Concerns\WithTitle;
use Maatwebsite\Excel\Events\AfterSheet;
use PhpOffice\PhpSpreadsheet\Cell\Coordinate;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;

/**
 * A report table (see ReportExportService) as an Excel sheet: a short heading
 * block (report, period, currency, filters, who generated it), a blank row,
 * the column header row, then the lines. Money cells are real numbers with a
 * "#,##0.00" format, never text with a currency symbol, so they add up in Excel.
 */
class ReportTableExport implements FromArray, ShouldAutoSize, WithColumnFormatting, WithEvents, WithStyles, WithTitle
{
    protected int $headerRow;

    public function __construct(protected array $table, protected User $user)
    {
        $this->headerRow = count($this->headingBlock()) + 2;
    }

    public function title(): string
    {
        // Sheet names are limited to 31 characters and can't contain : \ / ? * [ ]
        return mb_substr(preg_replace('/[:\\\\\/?*\[\]]/', '', $this->table['title']), 0, 31);
    }

    public function array(): array
    {
        $rows = array_map(fn ($line) => [$line], $this->headingBlock());
        $rows[] = [];
        $rows[] = array_column($this->table['columns'], 'label');

        $export = app(\App\Services\Reporting\Export\ReportExportService::class);
        foreach ($this->table['rows'] as $row) {
            $rows[] = array_map(fn ($c) => $export->plain($row[$c['key']] ?? null, $c['type']), $this->table['columns']);
        }

        return $rows;
    }

    public function columnFormats(): array
    {
        $formats = [];
        foreach ($this->table['columns'] as $i => $column) {
            $letter = Coordinate::stringFromColumnIndex($i + 1);
            $formats[$letter] = match ($column['type']) {
                'money' => '#,##0.00;-#,##0.00',
                'percent' => '0.00',
                'number' => '#,##0.##',
                default => null,
            };
        }

        return array_filter($formats);
    }

    public function styles(Worksheet $sheet): array
    {
        $styles = [1 => ['font' => ['bold' => true, 'size' => 13]], $this->headerRow => ['font' => ['bold' => true]]];
        foreach ($this->table['rows'] as $i => $row) {
            if (in_array($row['_style'] ?? null, ['section', 'subtotal', 'total'], true)) {
                $styles[$this->headerRow + 1 + $i] = ['font' => ['bold' => true]];
            }
        }

        return $styles;
    }

    public function registerEvents(): array
    {
        return [
            AfterSheet::class => function (AfterSheet $event) {
                // Keep the column headings visible while scrolling.
                $event->sheet->getDelegate()->freezePane('A'.($this->headerRow + 1));
            },
        ];
    }

    /** @return array<int, string> */
    protected function headingBlock(): array
    {
        $lines = [$this->table['title']];
        if ($this->table['period']) {
            $lines[] = 'Period: '.$this->table['period'];
        }
        if ($this->table['currency']) {
            $lines[] = 'Currency: '.$this->table['currency'];
        }
        foreach ($this->table['filters'] as $label => $value) {
            $lines[] = "{$label}: {$value}";
        }
        $lines[] = 'Generated by '.$this->user->name.' on '.now()->format('Y-m-d H:i');

        return $lines;
    }
}
